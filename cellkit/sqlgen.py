"""Migration and role SQL generated from a cell spec.

The first migration of a cell (``migrations/0001_<cell>.sql``) is generated
once and then committed; later changes are new hand-written migrations, never
a regenerated 0001 (applied migrations are checksummed).

Every table belongs to a workspace and is visible only while the transaction
is bound to it (``app.workspace_id``, forced row-level security). Ids are
identities starting above ``LEGACY_LIMIT`` so imported rows can keep their old
ids (references from other cells stay valid).
"""

from __future__ import annotations

import json

from cellkit.spec import LEGACY_LIMIT, Cell, Field, Resource


def _literal(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, dict)):
        return "'" + json.dumps(value).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def column(cell: Cell, f: Field) -> str:
    sql_type = {"text": "text", "int": "integer", "bigint": "bigint", "real": "double precision", "bool": "boolean",
                "date": "date", "timestamp": "timestamptz", "json": "jsonb", "enum": "text", "ref": "bigint"}[f.type]
    parts = [f"{f.name:<24} {sql_type}"]
    if f.required or f.default is not None:
        parts.append("NOT NULL")
    if f.default is not None:
        parts.append(f"DEFAULT {_literal(f.default)}")
    checks = []
    if f.type == "enum":
        checks.append(f"{f.name} IN ({', '.join(_literal(v) for v in f.values)})")
    if f.type == "text" and f.max_length:
        checks.append(f"length({f.name}) <= {int(f.max_length)}")
    if f.type == "text" and f.required:
        checks.append(f"length({f.name}) >= 1")
    if f.type in ("int", "bigint", "real") and f.min is not None:
        checks.append(f"{f.name} >= {f.min}")
    if f.type in ("int", "bigint", "real") and f.max is not None:
        checks.append(f"{f.name} <= {f.max}")
    if f.type == "json" and f.json_kind:
        checks.append(f"jsonb_typeof({f.name}) = '{f.json_kind}'")
    if checks:
        body = " AND ".join(checks)
        parts.append(f"CHECK ({f.name} IS NULL OR ({body}))" if not (f.required or f.default is not None)
                     else f"CHECK ({body})")
    return " ".join(parts)


def table(cell: Cell, r: Resource) -> str:
    s = cell.schema
    lines = ["workspace_id             uuid NOT NULL",
             f"id                       bigint GENERATED BY DEFAULT AS IDENTITY (START WITH {LEGACY_LIMIT})",
             "legacy_id                bigint"]
    lines += [column(cell, f) for f in r.fields]
    lines += ["version                  bigint NOT NULL DEFAULT 1",
              "created_at               timestamptz NOT NULL DEFAULT now()",
              "updated_at               timestamptz NOT NULL DEFAULT now()",
              "PRIMARY KEY (workspace_id, id)"]
    for f in r.fields:
        if f.unique:
            lines.append(f"UNIQUE (workspace_id, {f.name})")
    for combo in r.unique:
        lines.append(f"UNIQUE (workspace_id, {', '.join(combo)})")
    for f in r.refs:
        target = cell.resource(f.to)
        lines.append(f"FOREIGN KEY (workspace_id, {f.name}) REFERENCES {s}.{target.table} (workspace_id, id)")
    out = [f"CREATE TABLE {s}.{r.table} (\n    " + ",\n    ".join(lines) + "\n);",
           f"CREATE UNIQUE INDEX {r.table}_legacy ON {s}.{r.table} (workspace_id, legacy_id)"
           " WHERE legacy_id IS NOT NULL;"]
    indexed = {f.name for f in r.refs} | set(r.filters)
    for name in sorted(indexed):
        out.append(f"CREATE INDEX {r.table}_{name} ON {s}.{r.table} (workspace_id, {name});")
    return "\n".join(out)


def migration(cell: Cell) -> str:
    s = cell.schema
    api, publisher = cell.role("api"), cell.role("publisher")
    names = [r.table for r in cell.ordered()]
    kinds = ", ".join(_literal(r.name) for r in cell.resources)
    parts = [
        f"-- {cell.title} cell ({cell.name}), generated by solo-cell-kit from cell.yaml.",
        "-- Every row belongs to a workspace and is visible only while the transaction",
        "-- is bound to it (app.workspace_id). Do not edit once applied; add a new migration.",
        "",
        f"CREATE SCHEMA {s};",
        "",
        f"CREATE FUNCTION {s}.current_workspace() RETURNS uuid",
        "LANGUAGE sql STABLE AS $$",
        "    SELECT nullif(current_setting('app.workspace_id', true), '')::uuid",
        "$$;",
        "",
    ]
    for r in cell.ordered():
        parts += [table(cell, r), ""]
    parts += [
        "-- Idempotent creates: a key reserves the record id before the platform execution starts.",
        f"CREATE TABLE {s}.create_keys (",
        "    workspace_id uuid NOT NULL,",
        "    actor        uuid NOT NULL,",
        f"    kind         text NOT NULL CHECK (kind IN ({kinds})),",
        "    key          text NOT NULL CHECK (length(key) BETWEEN 8 AND 200),",
        "    record_id    bigint NOT NULL,",
        "    created_at   timestamptz NOT NULL DEFAULT now(),",
        "    PRIMARY KEY (workspace_id, actor, kind, key)",
        ");",
        "",
        "-- Graph events, written in the same transaction as the change (at-least-once delivery).",
        f"CREATE TABLE {s}.outbox (",
        "    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),",
        "    workspace_id    uuid NOT NULL,",
        "    type            text NOT NULL,",
        "    subject         text NOT NULL,",
        "    execution_id    uuid,",
        "    classification  text NOT NULL DEFAULT 'confidential',",
        "    payload         jsonb NOT NULL,",
        "    occurred_at     timestamptz NOT NULL DEFAULT now(),",
        "    published_at    timestamptz,",
        "    attempts        integer NOT NULL DEFAULT 0,",
        "    next_attempt_at timestamptz NOT NULL DEFAULT now(),",
        "    last_error      text,",
        "    correlation_id  text",
        ");",
        f"CREATE INDEX outbox_pending ON {s}.outbox (next_attempt_at) WHERE published_at IS NULL;",
        "",
        "DO $$",
        "DECLARE",
        "    t text;",
        "BEGIN",
        f"    FOREACH t IN ARRAY ARRAY[{', '.join(_literal(n) for n in [*names, 'create_keys', 'outbox'])}] LOOP",
        f"        EXECUTE format('ALTER TABLE {s}.%I ENABLE ROW LEVEL SECURITY', t);",
        f"        EXECUTE format('ALTER TABLE {s}.%I FORCE ROW LEVEL SECURITY', t);",
        f"        EXECUTE format('CREATE POLICY workspace_isolation ON {s}.%I'",
        f"                       ' USING (workspace_id = {s}.current_workspace())'",
        f"                       ' WITH CHECK (workspace_id = {s}.current_workspace())', t);",
        "    END LOOP;",
        "END",
        "$$;",
        "",
        f"GRANT USAGE ON SCHEMA {s} TO {api};",
        f"GRANT EXECUTE ON FUNCTION {s}.current_workspace() TO {api};",
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON {', '.join(f'{s}.{n}' for n in names)} TO {api};",
        f"GRANT USAGE ON SEQUENCE {', '.join(f'{s}.{n}_id_seq' for n in names)} TO {api};",
        f"GRANT SELECT, INSERT ON {s}.create_keys TO {api};",
        f"GRANT SELECT, INSERT ON {s}.outbox TO {api};",
        f"GRANT UPDATE (execution_id, published_at, attempts, next_attempt_at, last_error) ON {s}.outbox TO {api};",
        "",
        "-- The publisher sweeps the outbox of one workspace per token; it reads past RLS for the outbox only.",
        f"CREATE POLICY publisher_sweep ON {s}.outbox TO {publisher} USING (true) WITH CHECK (true);",
        f"GRANT USAGE ON SCHEMA {s} TO {publisher};",
        f"GRANT SELECT ON {s}.outbox TO {publisher};",
        f"GRANT UPDATE (published_at, attempts, next_attempt_at, last_error) ON {s}.outbox TO {publisher};",
        "",
    ]
    return "\n".join(parts)


def roles(cell: Cell) -> str:
    migrator, api, publisher = cell.role("migrator"), cell.role("api"), cell.role("publisher")
    return f"""-- Roles for the {cell.name} database. Locally a superuser runs this; on Neon
-- `{cell.name}-db provision` creates the same roles through the migrator.
--
-- {migrator}  owns the schema and runs migrations only.
-- {api}       the API at runtime: no superuser, no BYPASSRLS, owns nothing.
-- {publisher} sweeps and marks the outbox across workspaces; nothing else.

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{migrator}') THEN
        CREATE ROLE {migrator} LOGIN NOSUPERUSER NOCREATEROLE NOBYPASSRLS;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{api}') THEN
        CREATE ROLE {api} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS NOINHERIT;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{publisher}') THEN
        CREATE ROLE {publisher} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS NOINHERIT;
    END IF;
END
$$;
"""
